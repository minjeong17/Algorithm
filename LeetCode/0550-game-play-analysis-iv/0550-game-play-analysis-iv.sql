SELECT ROUND(COUNT(DISTINCT A.PLAYER_ID) / (SELECT COUNT(DISTINCT PLAYER_ID) AS TOTAL_PLAYER FROM ACTIVITY), 2) AS FRACTION
 FROM ACTIVITY A
 JOIN (SELECT PLAYER_ID, MIN(EVENT_DATE) AS MIN_DATE
        FROM ACTIVITY
        GROUP BY PLAYER_ID) AS J ON A.PLAYER_ID = J.PLAYER_ID
 WHERE DATE_ADD(J.MIN_DATE, INTERVAL 1 DAY) = A.EVENT_DATE
