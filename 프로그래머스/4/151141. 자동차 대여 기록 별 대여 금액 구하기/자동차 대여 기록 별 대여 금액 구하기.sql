SELECT T.HISTORY_ID, T.DAILY_FEE * ((100 - IFNULL(P.DISCOUNT_RATE, 0)) / 100) * T.DAYS AS FEE
 FROM (SELECT H.HISTORY_ID, H.CAR_ID, DATEDIFF(H.END_DATE, H.START_DATE) + 1 AS DAYS, C.CAR_TYPE, C.DAILY_FEE
        FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY H
        LEFT JOIN CAR_RENTAL_COMPANY_CAR C ON H.CAR_ID = C.CAR_ID
        WHERE C.CAR_TYPE = '트럭') T
 LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN P ON T.CAR_TYPE = P.CAR_TYPE
            AND P.DURATION_TYPE = (CASE WHEN T.DAYS >= 90 THEN '90일 이상'
                                       WHEN T.DAYS >= 30 THEN '30일 이상'
                                       WHEN T.DAYS >= 7 THEN '7일 이상'
                                  END)
 ORDER BY FEE DESC, HISTORY_ID DESC
;